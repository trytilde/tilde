// Writes sdk/ts/packages/iac/src/catalog.ts from the provider catalog of a disposable Tilde:
// one typed provider per built-in provider, with its connection types and the tools it ships as
// string-literal unions. MCP-served types list live servers, so they are left to org-specific
// codegen; their tools stay plain strings. Run through `task iac:catalog` (needs Postgres).
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

assert(process.env.TEST_DATABASE_URL, "TEST_DATABASE_URL required");
const env = {
  ...process.env,
  DATABASE_URL: process.env.TEST_DATABASE_URL,
  ENGINE_ENCRYPTION_BACKEND: "seed",
  ENGINE_ENCRYPTION_KEY: randomBytes(32).toString("base64"),
  ENGINE_KMS_KEY_ID: "",
  ENGINE_SERVE: "management",
  ENGINE_WEB_ENABLED: "false",
  RUST_LOG: "tilde=info",
};
const child = spawn(
  resolve(process.env.ENGINE_TEST_BINARY ?? "target/debug/tilde"),
  ["--listen", "127.0.0.1:0"],
  {
    env,
    stdio: ["ignore", "pipe", "pipe"],
  },
);
let logs = "";
await new Promise((done, fail) => {
  const timer = setTimeout(() => fail(new Error(`startup timeout\n${logs}`)), 30000);
  const read = (chunk) => {
    logs += chunk;
    if (logs.includes("tilde listening")) {
      clearTimeout(timer);
      done();
    }
  };
  child.stdout.on("data", read);
  child.stderr.on("data", read);
  child.once("exit", () => fail(new Error(logs)));
});
const origin = `http://${logs.match(/ address=(127\.0\.0\.1:\d+)/)[1]}`;
async function call(method, body) {
  const response = await fetch(`${origin}/tilde.management.v1.${method}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  if (!response.ok) throw new Error(`${method}: ${response.status} ${await response.text()}`);
  return response.json();
}

try {
  const providers = [];
  let pageToken = "";
  do {
    const page = await call("ConnectionsService/ListProviders", {
      pageSize: 200,
      pageToken,
      source: "PROVIDER_SOURCE_CATALOG",
    });
    providers.push(...(page.providers ?? []).filter((p) => p.builtIn));
    pageToken = page.nextPageToken ?? "";
  } while (pageToken);
  providers.sort((a, b) => (a.id < b.id ? -1 : 1));

  const camel = (id) => id.replace(/[-_]([a-z0-9])/g, (_, c) => c.toUpperCase());
  const pascal = (id) => camel(id).replace(/^./, (c) => c.toUpperCase());
  const union = (names) =>
    names.length ? names.map((n) => JSON.stringify(n)).join(" | ") : "never";
  const lines = [
    "// Generated by `task iac:catalog` from Tilde's built-in provider catalog. Do not edit.",
    "// Tool names of MCP-served connection types are not listed: pass them to `untypedTools`.",
    'import { catalogProvider } from "./refs.js";',
    "",
  ];
  for (const provider of providers) {
    const types = (provider.connectionTypes ?? []).map((t) => t.id).sort();
    const builtInTools = (provider.connectionTypes ?? []).some(
      (t) => !t.mcpServer && (t.capabilities ?? []).includes("CAPABILITY_TOOL"),
    );
    const tools = builtInTools
      ? (await call("ToolService/ListProviderTools", { providerId: provider.id })).tools
          .map((t) => t.name)
          .sort()
      : [];
    const name = pascal(provider.id);
    lines.push(
      `/** ${provider.name}: connections \`${provider.id}/<name>\`. */`,
      `export type ${name}Tool = ${union(tools)};`,
      `export type ${name}Type = ${union(types)};`,
      `export const ${camel(provider.id)} = catalogProvider<${name}Tool, ${name}Type>(${JSON.stringify(provider.id)});`,
      "",
    );
  }
  writeFileSync("sdk/ts/packages/iac/src/catalog.ts", lines.join("\n"));
  console.log(`Wrote ${providers.length} providers to sdk/ts/packages/iac/src/catalog.ts`);
} finally {
  child.kill();
}
